/** Same shape as `en`, with any string / function values (used to type other languages). */
type Widen<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends string
    ? string
    : { [K in keyof T]: Widen<T[K]> };

export type Messages = Widen<typeof en>;
